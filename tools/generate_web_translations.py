"""Generate the shared browser dictionary from Lua translations and WebView additions."""
from pathlib import Path
import argparse
import json
import re

root = Path(__file__).resolve().parents[1]
source = (root / "src/lua/00_bootstrap.lua").read_text(encoding="utf-8")
source = source[source.index("I18N_EN = {"):source.index("I18N_PATTERNS_EN = {")]
translations = {}
for key, value in re.findall(r'\["((?:[^"\\]|\\.)*)"\]\s*=\s*"((?:[^"\\]|\\.)*)"', source):
    translations[json.loads('"' + key + '"')] = json.loads('"' + value + '"')
translations.update(json.loads((root / "tools/web_translation_overrides.json").read_text(encoding="utf-8")))
content = "// Generated by tools/generate_web_translations.py; edit the sources, not this file.\nexport default " + json.dumps(translations, ensure_ascii=False, sort_keys=True, indent=2) + ";\n"
target = root / "src/web/translations.en.js"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    assert target.read_text(encoding="utf-8") == content, "Web translations need regeneration"
else:
    target.write_text(content, encoding="utf-8", newline="\n")
print(f"Web translations: {len(translations)} entries")
